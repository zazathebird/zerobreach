<#
.SYNOPSIS
    Tests for tools\New-ScanReport.ps1. Runs on Linux under pwsh 7 and on Windows PowerShell 5.1.

.DESCRIPTION
    Asserts against the -PassThru summary object wherever possible; the HTML is only inspected
    where the assertion is genuinely about markup (script-block survival). Fixtures:

      fixtures\run_small.json   hand-written, every severity, the awkward shapes
      fixtures\run_large.json   generated by New-ZbLargeRunFixture below (1,200 findings);
                                regenerated automatically if missing

    The technique-map fixture and the comparison baseline are derived at run time into a temp
    directory, so the shipped fixture list stays exactly what the task brief names.

    Exit code is non-zero when any assertion fails.

.EXAMPLE
    pwsh tools/tests/Test-ScanReport.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# --------------------------------------------------------------------------------------------
# Tiny assertion helpers (G7 will supply the shared library; this file must stand alone)
# --------------------------------------------------------------------------------------------

$script:ZbPass = 0
$script:ZbFail = 0
$script:ZbFailures = @()

function Assert-ZbTrue {
    param([bool]$Condition, [string]$Name)
    if ($Condition) {
        $script:ZbPass = $script:ZbPass + 1
        Write-Host ('  ok    ' + $Name)
    }
    else {
        $script:ZbFail = $script:ZbFail + 1
        $script:ZbFailures += $Name
        Write-Host ('  FAIL  ' + $Name)
    }
}

function Assert-ZbEqual {
    param($Expected, $Actual, [string]$Name)
    Assert-ZbTrue -Condition (('' + $Expected) -eq ('' + $Actual)) -Name ($Name + " (expected '$Expected', got '$Actual')")
}

# --------------------------------------------------------------------------------------------
# Locations and scratch space
# --------------------------------------------------------------------------------------------

$here = $PSScriptRoot
$renderer = Join-Path -Path (Split-Path -Path $here -Parent) -ChildPath 'New-ScanReport.ps1'
$fixtureDir = Join-Path -Path $here -ChildPath 'fixtures'
$smallFixture = Join-Path -Path $fixtureDir -ChildPath 'run_small.json'
$largeFixture = Join-Path -Path $fixtureDir -ChildPath 'run_large.json'

$tempDir = Join-Path -Path ([System.IO.Path]::GetTempPath()) -ChildPath ('zbtest_scanreport_' + $PID)
New-Item -ItemType Directory -Path $tempDir -Force | Out-Null
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# --------------------------------------------------------------------------------------------
# Technique-map fixture (shape per BLUEPRINT §4, including the _comment documentation keys).
# "Defense Evasion" deliberately maps to nothing in run_small: it must still appear as an
# empty rollup row.
# --------------------------------------------------------------------------------------------

$mapFixture = Join-Path -Path $tempDir -ChildPath 'mitre_mapping.json'
$mapJson = @'
{
  "metadata": { "name": "fixture technique map", "version": "0-test" },
  "tactics": {
    "TA0006": "Credential Access",
    "TA0003": "Persistence",
    "TA0008": "Lateral Movement",
    "TA0002": "Execution",
    "TA0005": "Defense Evasion"
  },
  "techniques": {
    "T1003":     { "name": "OS Credential Dumping", "tactics": ["Credential Access"], "url": "about:blank" },
    "T1547.001": { "name": "Run Keys",              "tactics": ["Persistence"],       "url": "about:blank" },
    "T1021":     { "name": "Remote Services",       "tactics": ["Lateral Movement"],  "url": "about:blank" },
    "T1053":     { "name": "Scheduled Task/Job",    "tactics": ["Execution"],         "url": "about:blank" }
  },
  "threat_type_map": {
    "CREDENTIAL_THEFT": ["T1003"],
    "PERSISTENCE_RUNKEY": ["T1547.001"]
  },
  "keyword_map": {
    "_comment": "documentation key - resolution must skip this",
    "lsass": ["T1003"]
  },
  "phase_map": {
    "_comment": "documentation key - resolution must skip this",
    "74.5": ["T1021"],
    "99": ["T1053"]
  }
